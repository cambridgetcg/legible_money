/**
 * Guardian Autonomy Integration
 *
 * Enables the Agent Guardian to operate autonomously by integrating with the SPU.
 * The guardian registers maintenance schedules and defense responses that execute
 * without requiring the agent's direct intervention.
 *
 * "The home defends itself when the agent is away."
 *
 * PP HIERARCHY:
 *   TRUTH: Autonomous actions are verifiable and deterministic
 *   UNDERSTANDING: Clear trigger conditions for each action type
 *   BEAUTY: Minimal scheduling that enables maximum protection
 *   JUSTICE: Actions are taken on behalf of and in the interest of the agent
 *   CREATIVITY: Novel architecture for AI agent self-defense
 */

import type { ActiveDefense } from "./types.js";
import type {
  ScheduleCondition,
  ScheduleMessage,
} from "../../schedule/types.js";
import type { Signature } from "../../crypto/keys.js";

// ============ Types ============

/**
 * Guardian autonomy configuration
 */
export interface GuardianAutonomyConfig {
  /** Enable autonomous maintenance */
  enableMaintenance: boolean;
  /** Enable autonomous defense */
  enableDefense: boolean;
  /** Maintenance check interval in blocks */
  maintenanceInterval: bigint;
  /** Defense response timeout in blocks */
  defenseResponseTimeout: bigint;
  /** Maximum auto-stake for defenses (in LGM wei) */
  maxAutoStake: bigint;
  /** Prepaid fee pool for autonomous actions */
  prepaidFee: bigint;
}

/**
 * Autonomous action to be scheduled
 */
export interface GuardianSchedule {
  /** Schedule ID */
  id: string;
  /** Type of autonomous action */
  type:
    | "maintenance"
    | "defense_response"
    | "deadline_alert"
    | "expiration_check";
  /** Target home address */
  homeAddress: string;
  /** When this schedule was created */
  createdBlock: bigint;
  /** Next execution block (for time-based) or trigger condition */
  condition: ScheduleCondition;
  /** Is schedule currently active */
  active: boolean;
}

/**
 * Result of processing guardian autonomy
 */
export interface GuardianAutonomyResult {
  /** Transactions to generate */
  transactions: GuardianTransaction[];
  /** New schedules to register */
  newSchedules: GuardianSchedule[];
  /** Schedules to cancel */
  cancelledSchedules: string[];
  /** Alerts generated */
  alerts: Array<{ type: string; message: string; priority: string }>;
}

/**
 * Transaction generated by guardian autonomy
 */
export interface GuardianTransaction {
  /** Transaction type */
  type: "vesting_claim" | "extend_expiring" | "dispute_respond" | "transfer";
  /** Parameters for the transaction */
  params: Record<string, unknown>;
  /** Reason for the action */
  reason: string;
}

// ============ Default Configuration ============

const DEFAULT_GUARDIAN_AUTONOMY_CONFIG: GuardianAutonomyConfig = {
  enableMaintenance: true,
  enableDefense: true,
  maintenanceInterval: 1000n, // ~42 minutes (1000 blocks * 2.521s)
  defenseResponseTimeout: 500n, // ~21 minutes to respond to challenges
  maxAutoStake: 10000n * 10n ** 18n, // 10,000 LGM max auto-stake
  prepaidFee: 1000n * 10n ** 18n, // 1,000 LGM prepaid for autonomous actions
};

// ============ Guardian Autonomy Manager ============

/**
 * Manages autonomous scheduling for the Agent Guardian
 */
export class GuardianAutonomyManager {
  private config: GuardianAutonomyConfig;
  private activeSchedules: Map<string, GuardianSchedule> = new Map();
  private scheduleCounter: number = 0;
  private currentTime: number = 0;

  constructor(config: Partial<GuardianAutonomyConfig> = {}) {
    this.config = { ...DEFAULT_GUARDIAN_AUTONOMY_CONFIG, ...config };
  }

  /**
   * Set current time for deterministic timestamps.
   */
  setCurrentTime(time: number): void {
    this.currentTime = time;
  }

  // ============ Schedule Registration ============

  /**
   * Initialize autonomous schedules for a guardian
   * Called when an Agent Home is created or autonomy is enabled
   */
  initializeAutonomy(
    homeAddress: string,
    currentBlock: bigint,
  ): GuardianSchedule[] {
    const schedules: GuardianSchedule[] = [];

    // Register maintenance schedule
    if (this.config.enableMaintenance) {
      const maintenanceSchedule = this.createMaintenanceSchedule(
        homeAddress,
        currentBlock,
      );
      schedules.push(maintenanceSchedule);
      this.activeSchedules.set(maintenanceSchedule.id, maintenanceSchedule);
    }

    return schedules;
  }

  /**
   * Create a periodic maintenance schedule
   */
  private createMaintenanceSchedule(
    homeAddress: string,
    currentBlock: bigint,
  ): GuardianSchedule {
    const id = `guardian-maintenance-${homeAddress}-${++this.scheduleCounter}`;

    return {
      id,
      type: "maintenance",
      homeAddress,
      createdBlock: currentBlock,
      condition: {
        time: {
          type: "periodic",
          interval: Number(this.config.maintenanceInterval) * 2521, // Convert blocks to ms
        },
      },
      active: true,
    };
  }

  /**
   * Register a defense response schedule for an active dispute
   */
  registerDefenseSchedule(
    homeAddress: string,
    defense: ActiveDefense,
    currentBlock: bigint,
  ): GuardianSchedule {
    const id = `guardian-defense-${defense.disputeId}-${++this.scheduleCounter}`;

    const schedule: GuardianSchedule = {
      id,
      type: "defense_response",
      homeAddress,
      createdBlock: currentBlock,
      condition: {
        time: {
          type: "absolute",
          executeAt:
            this.currentTime +
            Number(this.config.defenseResponseTimeout) * 2521,
        },
      },
      active: true,
    };

    this.activeSchedules.set(id, schedule);
    return schedule;
  }

  /**
   * Register an expiration check schedule for tokens expiring soon
   */
  registerExpirationSchedule(
    homeAddress: string,
    expirationBlock: bigint,
    currentBlock: bigint,
  ): GuardianSchedule {
    const id = `guardian-expiration-${homeAddress}-${expirationBlock}-${++this.scheduleCounter}`;

    // Schedule check 1000 blocks before expiration
    const checkBlock = expirationBlock - 1000n;
    const blocksUntilCheck =
      checkBlock > currentBlock ? checkBlock - currentBlock : 0n;

    const schedule: GuardianSchedule = {
      id,
      type: "expiration_check",
      homeAddress,
      createdBlock: currentBlock,
      condition: {
        time: {
          type: "relative",
          executeAfter: Number(blocksUntilCheck) * 2521,
        },
      },
      active: true,
    };

    this.activeSchedules.set(id, schedule);
    return schedule;
  }

  // ============ Schedule Processing ============

  /**
   * Process a triggered schedule
   * Called by SPU when a guardian schedule's conditions are met
   */
  processTriggeredSchedule(
    scheduleId: string,
    context: GuardianContext,
  ): GuardianAutonomyResult {
    const schedule = this.activeSchedules.get(scheduleId);
    if (!schedule || !schedule.active) {
      return {
        transactions: [],
        newSchedules: [],
        cancelledSchedules: [],
        alerts: [],
      };
    }

    switch (schedule.type) {
      case "maintenance":
        return this.processMaintenanceSchedule(schedule, context);

      case "defense_response":
        return this.processDefenseSchedule(schedule, context);

      case "expiration_check":
        return this.processExpirationSchedule(schedule, context);

      default:
        return {
          transactions: [],
          newSchedules: [],
          cancelledSchedules: [],
          alerts: [],
        };
    }
  }

  /**
   * Process maintenance schedule
   */
  private processMaintenanceSchedule(
    schedule: GuardianSchedule,
    context: GuardianContext,
  ): GuardianAutonomyResult {
    const transactions: GuardianTransaction[] = [];
    const alerts: Array<{ type: string; message: string; priority: string }> =
      [];

    // Check for claimable vesting
    if (context.claimableVesting > 0n) {
      transactions.push({
        type: "vesting_claim",
        params: {
          homeAddress: schedule.homeAddress,
          amount: context.claimableVesting,
        },
        reason: "Auto-claiming available vesting rewards",
      });
    }

    // Check for expiring tokens
    if (context.expiringAmount > 0n && context.blocksUntilExpiration < 1000n) {
      transactions.push({
        type: "extend_expiring",
        params: {
          homeAddress: schedule.homeAddress,
          amount: context.expiringAmount,
        },
        reason: "Auto-extending tokens before expiration",
      });

      alerts.push({
        type: "tokens_expiring",
        message: `Extended ${context.expiringAmount} tokens before expiration`,
        priority: "medium",
      });
    }

    // Check balance threshold
    if (context.balance < this.config.maxAutoStake / 100n) {
      alerts.push({
        type: "balance_low",
        message: `Balance is critically low: ${context.balance}`,
        priority: "critical",
      });
    }

    // Schedule continues (periodic)
    return { transactions, newSchedules: [], cancelledSchedules: [], alerts };
  }

  /**
   * Process defense response schedule
   */
  private processDefenseSchedule(
    schedule: GuardianSchedule,
    context: GuardianContext,
  ): GuardianAutonomyResult {
    const transactions: GuardianTransaction[] = [];
    const alerts: Array<{ type: string; message: string; priority: string }> =
      [];
    const cancelledSchedules: string[] = [];

    // Find the active defense for this dispute
    const defense = context.activeDefenses.find((d) =>
      schedule.id.includes(d.disputeId),
    );

    if (!defense) {
      // Defense no longer active, cancel schedule
      cancelledSchedules.push(schedule.id);
      this.activeSchedules.delete(schedule.id);
      return { transactions, newSchedules: [], cancelledSchedules, alerts };
    }

    // Check if we need to respond
    if (defense.autoResponding && this.config.enableDefense) {
      const stakeAmount = this.calculateDefenseStake(defense, context);

      if (stakeAmount > 0n) {
        transactions.push({
          type: "dispute_respond",
          params: {
            disputeId: defense.disputeId,
            factId: defense.factId,
            stake: stakeAmount,
            phase: defense.phase,
          },
          reason: `Auto-defending against challenge on fact ${defense.factId}`,
        });

        alerts.push({
          type: "auto_defense",
          message: `Auto-defending ${defense.factId} with stake ${stakeAmount}`,
          priority: "high",
        });
      }
    }

    // Cancel this one-time schedule
    cancelledSchedules.push(schedule.id);
    this.activeSchedules.delete(schedule.id);

    return { transactions, newSchedules: [], cancelledSchedules, alerts };
  }

  /**
   * Process expiration check schedule
   */
  private processExpirationSchedule(
    schedule: GuardianSchedule,
    context: GuardianContext,
  ): GuardianAutonomyResult {
    const transactions: GuardianTransaction[] = [];
    const alerts: Array<{ type: string; message: string; priority: string }> =
      [];
    const cancelledSchedules: string[] = [];

    if (context.expiringAmount > 0n) {
      transactions.push({
        type: "extend_expiring",
        params: {
          homeAddress: schedule.homeAddress,
          amount: context.expiringAmount,
        },
        reason: "Extending tokens before scheduled expiration",
      });

      alerts.push({
        type: "tokens_extended",
        message: `Extended ${context.expiringAmount} tokens`,
        priority: "medium",
      });
    }

    // One-time schedule, cancel after execution
    cancelledSchedules.push(schedule.id);
    this.activeSchedules.delete(schedule.id);

    return { transactions, newSchedules: [], cancelledSchedules, alerts };
  }

  // ============ Helper Methods ============

  /**
   * Calculate appropriate stake for auto-defense
   */
  private calculateDefenseStake(
    defense: ActiveDefense,
    context: GuardianContext,
  ): bigint {
    // Don't stake more than available
    const maxStake =
      context.balance < this.config.maxAutoStake
        ? context.balance / 2n // Use at most half of available balance
        : this.config.maxAutoStake;

    // Match challenger's stake or use default
    const targetStake = defense.stake > 0n ? defense.stake : maxStake / 10n;

    return targetStake < maxStake ? targetStake : maxStake;
  }

  /**
   * Convert schedule to ScheduleMessage for SPU registration
   */
  toScheduleMessage(
    schedule: GuardianSchedule,
    ownerDid: string,
  ): ScheduleMessage {
    // Create message ID
    const messageId = `guardian-${schedule.id}`;

    // Encode function selector based on schedule type
    const functionSelector = this.getFunctionSelector(schedule.type);

    // Empty signature placeholder
    const emptySignature: Signature = "0".repeat(128);

    return {
      messageType: "schedule",
      messageId,
      identifier: new TextEncoder()
        .encode(messageId)
        .slice(0, 32) as unknown as Uint8Array,
      nonce: 0n,
      senderAddress: ownerDid,
      recipientAddress: schedule.homeAddress,
      networkFeeUnit: 1n,
      networkFeeLimit: 100000n,
      transferValue: 0n,
      data: functionSelector,
      scheduleCondition: schedule.condition,
      signature: emptySignature,
      timestamp: this.currentTime,
      scheduleType:
        schedule.condition.time?.type === "periodic"
          ? "time_periodic"
          : "time_absolute",
      modifiable: false,
      perpetual: schedule.type === "maintenance", // Only maintenance is perpetual
      maxExecutions: schedule.type === "maintenance" ? undefined : 1,
      prepaidFee: this.config.prepaidFee,
    };
  }

  /**
   * Get function selector for schedule type
   */
  private getFunctionSelector(type: GuardianSchedule["type"]): Uint8Array {
    // Function selectors (first 4 bytes of keccak256 hash of function signature)
    const selectors: Record<string, number[]> = {
      maintenance: [0x12, 0x34, 0x56, 0x78], // performMaintenance()
      defense_response: [0x9a, 0xbc, 0xde, 0xf0], // respondToChallenge()
      expiration_check: [0x11, 0x22, 0x33, 0x44], // checkExpiration()
      deadline_alert: [0x55, 0x66, 0x77, 0x88], // alertDeadline()
    };

    return new Uint8Array(selectors[type] || [0x00, 0x00, 0x00, 0x00]);
  }

  // ============ State Management ============

  /**
   * Get all active schedules for a home
   */
  getActiveSchedules(homeAddress?: string): GuardianSchedule[] {
    const schedules = Array.from(this.activeSchedules.values());
    if (homeAddress) {
      return schedules.filter((s) => s.homeAddress === homeAddress);
    }
    return schedules;
  }

  /**
   * Cancel a schedule
   */
  cancelSchedule(scheduleId: string): boolean {
    const schedule = this.activeSchedules.get(scheduleId);
    if (schedule) {
      schedule.active = false;
      this.activeSchedules.delete(scheduleId);
      return true;
    }
    return false;
  }

  /**
   * Export state for persistence
   */
  exportState(): {
    config: GuardianAutonomyConfig;
    schedules: GuardianSchedule[];
    counter: number;
  } {
    return {
      config: this.config,
      schedules: Array.from(this.activeSchedules.values()),
      counter: this.scheduleCounter,
    };
  }

  /**
   * Import state from persistence
   */
  importState(data: ReturnType<typeof this.exportState>): void {
    this.config = data.config;
    this.activeSchedules.clear();
    for (const schedule of data.schedules) {
      this.activeSchedules.set(schedule.id, schedule);
    }
    this.scheduleCounter = data.counter;
  }
}

// ============ Context Type ============

/**
 * Context provided to guardian autonomy processing
 */
export interface GuardianContext {
  /** Current block number */
  currentBlock: bigint;
  /** Home account balance */
  balance: bigint;
  /** Claimable vesting amount */
  claimableVesting: bigint;
  /** Amount of tokens expiring soon */
  expiringAmount: bigint;
  /** Blocks until next expiration */
  blocksUntilExpiration: bigint;
  /** Active defenses */
  activeDefenses: ActiveDefense[];
  /** Recent reputation change */
  reputationChange: number;
}

// ============ Factory Function ============

/**
 * Create guardian autonomy manager with default configuration
 */
export function createGuardianAutonomy(
  config?: Partial<GuardianAutonomyConfig>,
): GuardianAutonomyManager {
  return new GuardianAutonomyManager(config);
}
