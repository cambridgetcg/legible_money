/**
 * Treasury Autonomy Integration
 *
 * Enables the Agent Treasury to operate autonomously by integrating with the SPU.
 * The treasury registers financial automation schedules that execute without
 * requiring the agent's direct intervention.
 *
 * "Resources managed automatically, securely."
 *
 * PP HIERARCHY:
 *   TRUTH: Autonomous actions are verifiable and deterministic
 *   UNDERSTANDING: Clear trigger conditions for each financial action
 *   BEAUTY: Minimal scheduling that enables maximum automation
 *   JUSTICE: Actions preserve agent's economic interests
 *   CREATIVITY: Novel architecture for autonomous agent economics
 */

import type {
  VestingPosition,
  StakingPosition,
  TreasuryAutomation,
} from "./types.js";
import type {
  ScheduleCondition,
  ScheduleMessage,
} from "../../schedule/types.js";
import type { Signature } from "../../crypto/keys.js";

// ============ Types ============

/**
 * Treasury autonomy configuration
 */
export interface TreasuryAutonomyConfig {
  /** Enable automatic vesting claims */
  enableVestingClaims: boolean;
  /** Enable automatic expiration extension */
  enableExpirationExtension: boolean;
  /** Enable automatic reward compounding */
  enableRewardCompounding: boolean;
  /** Check interval in blocks */
  checkInterval: bigint;
  /** Minimum claim threshold (in LGM wei) */
  minClaimThreshold: bigint;
  /** Blocks before expiration to trigger extension */
  expirationWarningBlocks: bigint;
  /** Prepaid fee pool for autonomous actions */
  prepaidFee: bigint;
}

/**
 * Treasury autonomous schedule
 */
export interface TreasurySchedule {
  /** Schedule ID */
  id: string;
  /** Type of autonomous action */
  type:
    | "vesting_check"
    | "expiration_check"
    | "compound_check"
    | "staking_monitor";
  /** Target home address */
  homeAddress: string;
  /** When this schedule was created */
  createdBlock: bigint;
  /** Schedule condition */
  condition: ScheduleCondition;
  /** Is schedule currently active */
  active: boolean;
  /** Related position ID (for position-specific schedules) */
  positionId?: string;
}

/**
 * Result of processing treasury autonomy
 */
export interface TreasuryAutonomyResult {
  /** Transactions to generate */
  transactions: TreasuryTransaction[];
  /** New schedules to register */
  newSchedules: TreasurySchedule[];
  /** Schedules to cancel */
  cancelledSchedules: string[];
  /** Notifications generated */
  notifications: Array<{ type: string; message: string; amount?: bigint }>;
}

/**
 * Transaction generated by treasury autonomy
 */
export interface TreasuryTransaction {
  /** Transaction type */
  type: "vesting_claim" | "extend_expiring" | "compound_rewards" | "restake";
  /** Parameters for the transaction */
  params: Record<string, unknown>;
  /** Reason for the action */
  reason: string;
  /** Amount involved */
  amount: bigint;
}

// ============ Default Configuration ============

const DEFAULT_TREASURY_AUTONOMY_CONFIG: TreasuryAutonomyConfig = {
  enableVestingClaims: true,
  enableExpirationExtension: true,
  enableRewardCompounding: false, // Off by default - requires explicit opt-in
  checkInterval: 500n, // ~21 minutes (500 blocks * 2.521s)
  minClaimThreshold: 10n * 10n ** 18n, // Only claim if >= 10 LGM available
  expirationWarningBlocks: 1000n, // Warn/extend 1000 blocks before expiration (~42 min)
  prepaidFee: 500n * 10n ** 18n, // 500 LGM prepaid for autonomous actions
};

// ============ Treasury Autonomy Manager ============

/**
 * Manages autonomous scheduling for the Agent Treasury
 */
export class TreasuryAutonomyManager {
  private config: TreasuryAutonomyConfig;
  private activeSchedules: Map<string, TreasurySchedule> = new Map();
  private scheduleCounter: number = 0;
  private currentTime: number = 0;

  constructor(config: Partial<TreasuryAutonomyConfig> = {}) {
    this.config = { ...DEFAULT_TREASURY_AUTONOMY_CONFIG, ...config };
  }

  /**
   * Set current time for deterministic timestamps.
   */
  setCurrentTime(time: number): void {
    this.currentTime = time;
  }

  // ============ Schedule Registration ============

  /**
   * Initialize autonomous schedules for a treasury
   * Called when an Agent Home is created or autonomy is enabled
   */
  initializeAutonomy(
    homeAddress: string,
    currentBlock: bigint,
    automation: TreasuryAutomation,
  ): TreasurySchedule[] {
    const schedules: TreasurySchedule[] = [];

    // Register vesting check schedule
    if (this.config.enableVestingClaims && automation.autoClaimVesting) {
      const vestingSchedule = this.createVestingSchedule(
        homeAddress,
        currentBlock,
      );
      schedules.push(vestingSchedule);
      this.activeSchedules.set(vestingSchedule.id, vestingSchedule);
    }

    // Register expiration check schedule
    if (
      this.config.enableExpirationExtension &&
      automation.autoExtendExpiring
    ) {
      const expirationSchedule = this.createExpirationSchedule(
        homeAddress,
        currentBlock,
      );
      schedules.push(expirationSchedule);
      this.activeSchedules.set(expirationSchedule.id, expirationSchedule);
    }

    // Register compound check schedule
    if (this.config.enableRewardCompounding && automation.autoCompoundRewards) {
      const compoundSchedule = this.createCompoundSchedule(
        homeAddress,
        currentBlock,
      );
      schedules.push(compoundSchedule);
      this.activeSchedules.set(compoundSchedule.id, compoundSchedule);
    }

    return schedules;
  }

  /**
   * Create a periodic vesting check schedule
   */
  private createVestingSchedule(
    homeAddress: string,
    currentBlock: bigint,
  ): TreasurySchedule {
    const id = `treasury-vesting-${homeAddress}-${++this.scheduleCounter}`;

    return {
      id,
      type: "vesting_check",
      homeAddress,
      createdBlock: currentBlock,
      condition: {
        time: {
          type: "periodic",
          interval: Number(this.config.checkInterval) * 2521, // Convert blocks to ms
        },
      },
      active: true,
    };
  }

  /**
   * Create a periodic expiration check schedule
   */
  private createExpirationSchedule(
    homeAddress: string,
    currentBlock: bigint,
  ): TreasurySchedule {
    const id = `treasury-expiration-${homeAddress}-${++this.scheduleCounter}`;

    return {
      id,
      type: "expiration_check",
      homeAddress,
      createdBlock: currentBlock,
      condition: {
        time: {
          type: "periodic",
          interval: Number(this.config.checkInterval) * 2521,
        },
      },
      active: true,
    };
  }

  /**
   * Create a periodic compound check schedule
   */
  private createCompoundSchedule(
    homeAddress: string,
    currentBlock: bigint,
  ): TreasurySchedule {
    const id = `treasury-compound-${homeAddress}-${++this.scheduleCounter}`;

    return {
      id,
      type: "compound_check",
      homeAddress,
      createdBlock: currentBlock,
      condition: {
        time: {
          type: "periodic",
          interval: Number(this.config.checkInterval) * 2521 * 2, // Check compounding less frequently
        },
      },
      active: true,
    };
  }

  /**
   * Register a staking position monitor
   */
  registerStakingMonitor(
    homeAddress: string,
    position: StakingPosition,
    currentBlock: bigint,
  ): TreasurySchedule {
    const id = `treasury-staking-${position.id}-${++this.scheduleCounter}`;

    const schedule: TreasurySchedule = {
      id,
      type: "staking_monitor",
      homeAddress,
      createdBlock: currentBlock,
      condition: {
        time: {
          type: "periodic",
          interval: Number(this.config.checkInterval) * 2521 * 4, // Check staking less frequently
        },
      },
      active: true,
      positionId: position.id,
    };

    this.activeSchedules.set(id, schedule);
    return schedule;
  }

  // ============ Schedule Processing ============

  /**
   * Process a triggered schedule
   * Called by SPU when a treasury schedule's conditions are met
   */
  processTriggeredSchedule(
    scheduleId: string,
    context: TreasuryContext,
  ): TreasuryAutonomyResult {
    const schedule = this.activeSchedules.get(scheduleId);
    if (!schedule || !schedule.active) {
      return {
        transactions: [],
        newSchedules: [],
        cancelledSchedules: [],
        notifications: [],
      };
    }

    switch (schedule.type) {
      case "vesting_check":
        return this.processVestingSchedule(schedule, context);

      case "expiration_check":
        return this.processExpirationSchedule(schedule, context);

      case "compound_check":
        return this.processCompoundSchedule(schedule, context);

      case "staking_monitor":
        return this.processStakingMonitor(schedule, context);

      default:
        return {
          transactions: [],
          newSchedules: [],
          cancelledSchedules: [],
          notifications: [],
        };
    }
  }

  /**
   * Process vesting check schedule
   */
  private processVestingSchedule(
    schedule: TreasurySchedule,
    context: TreasuryContext,
  ): TreasuryAutonomyResult {
    const transactions: TreasuryTransaction[] = [];
    const notifications: Array<{
      type: string;
      message: string;
      amount?: bigint;
    }> = [];

    // Calculate total claimable across all vesting positions
    let totalClaimable = 0n;
    const claimablePositions: VestingPosition[] = [];

    for (const position of context.vestingPositions) {
      const claimable = this.calculateClaimableVesting(
        position,
        context.currentBlock,
      );
      if (claimable > 0n) {
        totalClaimable += claimable;
        claimablePositions.push(position);
      }
    }

    // Check if above minimum threshold
    if (totalClaimable >= this.config.minClaimThreshold) {
      // Create individual claim transactions for each position
      for (const position of claimablePositions) {
        const claimable = this.calculateClaimableVesting(
          position,
          context.currentBlock,
        );
        if (claimable > 0n) {
          transactions.push({
            type: "vesting_claim",
            params: {
              homeAddress: schedule.homeAddress,
              vestingId: position.vestingId,
              amount: claimable,
            },
            reason: `Auto-claiming vesting rewards for claim ${position.claimId}`,
            amount: claimable,
          });
        }
      }

      notifications.push({
        type: "vesting_claimed",
        message: `Auto-claimed ${totalClaimable} wei from ${claimablePositions.length} vesting positions`,
        amount: totalClaimable,
      });
    }

    // Schedule continues (periodic)
    return {
      transactions,
      newSchedules: [],
      cancelledSchedules: [],
      notifications,
    };
  }

  /**
   * Process expiration check schedule
   */
  private processExpirationSchedule(
    schedule: TreasurySchedule,
    context: TreasuryContext,
  ): TreasuryAutonomyResult {
    const transactions: TreasuryTransaction[] = [];
    const notifications: Array<{
      type: string;
      message: string;
      amount?: bigint;
    }> = [];

    // Check for tokens expiring soon
    if (
      context.expiringAmount > 0n &&
      context.blocksUntilExpiration < this.config.expirationWarningBlocks
    ) {
      transactions.push({
        type: "extend_expiring",
        params: {
          homeAddress: schedule.homeAddress,
          amount: context.expiringAmount,
          currentExpiration:
            context.currentBlock + context.blocksUntilExpiration,
        },
        reason: "Auto-extending tokens before expiration",
        amount: context.expiringAmount,
      });

      notifications.push({
        type: "tokens_extended",
        message: `Auto-extended ${context.expiringAmount} wei before expiration`,
        amount: context.expiringAmount,
      });
    } else if (context.expiringAmount > 0n) {
      // Tokens expiring but not yet critical - just notify
      notifications.push({
        type: "tokens_expiring_soon",
        message: `${context.expiringAmount} wei expiring in ${context.blocksUntilExpiration} blocks`,
        amount: context.expiringAmount,
      });
    }

    // Schedule continues (periodic)
    return {
      transactions,
      newSchedules: [],
      cancelledSchedules: [],
      notifications,
    };
  }

  /**
   * Process compound check schedule
   */
  private processCompoundSchedule(
    schedule: TreasurySchedule,
    context: TreasuryContext,
  ): TreasuryAutonomyResult {
    const transactions: TreasuryTransaction[] = [];
    const notifications: Array<{
      type: string;
      message: string;
      amount?: bigint;
    }> = [];

    // Check if we have rewards to compound and enough liquid balance
    if (
      context.pendingRewards > this.config.minClaimThreshold &&
      context.liquidBalance > context.minimumLiquidBalance
    ) {
      // Calculate amount to compound (keep minimum liquid, compound the rest)
      const amountToCompound = context.pendingRewards;

      transactions.push({
        type: "compound_rewards",
        params: {
          homeAddress: schedule.homeAddress,
          amount: amountToCompound,
          targetValidator: context.preferredValidator,
        },
        reason: "Auto-compounding verification rewards",
        amount: amountToCompound,
      });

      notifications.push({
        type: "rewards_compounded",
        message: `Auto-compounded ${amountToCompound} wei into staking`,
        amount: amountToCompound,
      });
    }

    // Schedule continues (periodic)
    return {
      transactions,
      newSchedules: [],
      cancelledSchedules: [],
      notifications,
    };
  }

  /**
   * Process staking position monitor
   */
  private processStakingMonitor(
    schedule: TreasurySchedule,
    context: TreasuryContext,
  ): TreasuryAutonomyResult {
    const transactions: TreasuryTransaction[] = [];
    const notifications: Array<{
      type: string;
      message: string;
      amount?: bigint;
    }> = [];
    const cancelledSchedules: string[] = [];

    // Find the staking position being monitored
    const position = context.stakingPositions.find(
      (p) => p.id === schedule.positionId,
    );

    if (!position) {
      // Position no longer exists, cancel monitor
      cancelledSchedules.push(schedule.id);
      this.activeSchedules.delete(schedule.id);
      return {
        transactions,
        newSchedules: [],
        cancelledSchedules,
        notifications,
      };
    }

    // Check validator status (if provided in context)
    if (
      position.validatorStatus === "jailed" ||
      position.validatorStatus === "tombstoned"
    ) {
      notifications.push({
        type: "validator_issue",
        message: `Staking position ${position.id} validator is ${position.validatorStatus}`,
        amount: position.amount,
      });
    }

    // Check if position has pending rewards
    if (
      position.pendingRewards &&
      position.pendingRewards > this.config.minClaimThreshold
    ) {
      notifications.push({
        type: "staking_rewards_available",
        message: `${position.pendingRewards} wei rewards available from staking position ${position.id}`,
        amount: position.pendingRewards,
      });
    }

    // Schedule continues (periodic)
    return {
      transactions,
      newSchedules: [],
      cancelledSchedules,
      notifications,
    };
  }

  // ============ Helper Methods ============

  /**
   * Calculate claimable amount from a vesting position
   * Uses the precomputed claimableAmount from VestingPosition
   */
  private calculateClaimableVesting(
    position: VestingPosition,
    _currentBlock: bigint,
  ): bigint {
    // Position must be actively vesting
    if (position.status !== "vesting") return 0n;

    // Use the precomputed claimable amount
    // (The vesting engine calculates this based on elapsed time and release schedule)
    return position.claimableAmount;
  }

  /**
   * Convert schedule to ScheduleMessage for SPU registration
   */
  toScheduleMessage(
    schedule: TreasurySchedule,
    ownerDid: string,
  ): ScheduleMessage {
    const messageId = `treasury-${schedule.id}`;
    const functionSelector = this.getFunctionSelector(schedule.type);
    const emptySignature: Signature = "0".repeat(128);

    return {
      messageType: "schedule",
      messageId,
      identifier: new TextEncoder()
        .encode(messageId)
        .slice(0, 32) as unknown as Uint8Array,
      nonce: 0n,
      senderAddress: ownerDid,
      recipientAddress: schedule.homeAddress,
      networkFeeUnit: 1n,
      networkFeeLimit: 100000n,
      transferValue: 0n,
      data: functionSelector,
      scheduleCondition: schedule.condition,
      signature: emptySignature,
      timestamp: this.currentTime,
      scheduleType: "time_periodic",
      modifiable: false,
      perpetual: true, // Treasury schedules are perpetual
      maxExecutions: undefined,
      prepaidFee: this.config.prepaidFee,
    };
  }

  /**
   * Get function selector for schedule type
   */
  private getFunctionSelector(type: TreasurySchedule["type"]): Uint8Array {
    const selectors: Record<string, number[]> = {
      vesting_check: [0x21, 0x43, 0x65, 0x87], // checkVesting()
      expiration_check: [0x32, 0x54, 0x76, 0x98], // checkExpiration()
      compound_check: [0x43, 0x65, 0x87, 0xa9], // checkCompound()
      staking_monitor: [0x54, 0x76, 0x98, 0xba], // monitorStaking()
    };

    return new Uint8Array(selectors[type] || [0x00, 0x00, 0x00, 0x00]);
  }

  // ============ State Management ============

  /**
   * Get all active schedules for a home
   */
  getActiveSchedules(homeAddress?: string): TreasurySchedule[] {
    const schedules = Array.from(this.activeSchedules.values());
    if (homeAddress) {
      return schedules.filter((s) => s.homeAddress === homeAddress);
    }
    return schedules;
  }

  /**
   * Cancel a schedule
   */
  cancelSchedule(scheduleId: string): boolean {
    const schedule = this.activeSchedules.get(scheduleId);
    if (schedule) {
      schedule.active = false;
      this.activeSchedules.delete(scheduleId);
      return true;
    }
    return false;
  }

  /**
   * Update configuration
   */
  updateConfig(config: Partial<TreasuryAutonomyConfig>): void {
    this.config = { ...this.config, ...config };
  }

  /**
   * Export state for persistence
   */
  exportState(): {
    config: TreasuryAutonomyConfig;
    schedules: TreasurySchedule[];
    counter: number;
  } {
    return {
      config: this.config,
      schedules: Array.from(this.activeSchedules.values()),
      counter: this.scheduleCounter,
    };
  }

  /**
   * Import state from persistence
   */
  importState(data: ReturnType<typeof this.exportState>): void {
    this.config = data.config;
    this.activeSchedules.clear();
    for (const schedule of data.schedules) {
      this.activeSchedules.set(schedule.id, schedule);
    }
    this.scheduleCounter = data.counter;
  }
}

// ============ Context Type ============

/**
 * Context provided to treasury autonomy processing
 */
export interface TreasuryContext {
  /** Current block number */
  currentBlock: bigint;
  /** Liquid (available) balance */
  liquidBalance: bigint;
  /** Minimum liquid balance to maintain */
  minimumLiquidBalance: bigint;
  /** Vesting positions */
  vestingPositions: VestingPosition[];
  /** Staking positions */
  stakingPositions: (StakingPosition & {
    validatorStatus?: "active" | "jailed" | "tombstoned";
    pendingRewards?: bigint;
  })[];
  /** Amount of tokens expiring soon */
  expiringAmount: bigint;
  /** Blocks until next expiration */
  blocksUntilExpiration: bigint;
  /** Pending verification rewards */
  pendingRewards: bigint;
  /** Preferred validator for compounding */
  preferredValidator?: string;
}

// ============ Factory Function ============

/**
 * Create treasury autonomy manager with default configuration
 */
export function createTreasuryAutonomy(
  config?: Partial<TreasuryAutonomyConfig>,
): TreasuryAutonomyManager {
  return new TreasuryAutonomyManager(config);
}
