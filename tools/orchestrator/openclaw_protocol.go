package orchestrator

import (
	"context"
	"encoding/json"
	"fmt"
)

// OpenClaw structured command types.
const (
	OCmdEvaluateClaim     = "evaluate_claim"
	OCmdIdentifyGaps      = "identify_gaps"
	OCmdAnalyzeReferences = "analyze_references"
	OCmdGenerateClaim     = "generate_claim"
	OCmdDeployContract    = "deploy_contract"
	OCmdCallContract      = "call_contract"
	OCmdQueryContract     = "query_contract"
)

// OpenClawRequest is the structured command sent to an OpenClaw session.
type OpenClawRequest struct {
	Type    string          `json:"type"`
	Payload json.RawMessage `json:"payload"`
}

// EvaluateClaimPayload is the payload for evaluate_claim commands.
type EvaluateClaimPayload struct {
	ClaimID         string               `json:"claim_id"`
	ClaimText       string               `json:"claim_text"`
	Domain          string               `json:"domain"`
	Category        string               `json:"category"`
	SupportingFacts []FactSummary        `json:"supporting_facts"`
	CounterFacts    []CounterFactSummary `json:"counter_facts"`
	DomainDensity   uint32               `json:"domain_density"`
	StratumCeiling  uint32               `json:"stratum_ceiling"`
	LogicZoneCap    uint32               `json:"logic_zone_cap"`
}

// FactSummary is a compact representation of a fact for OpenClaw context.
type FactSummary struct {
	ID         string `json:"id"`
	Text       string `json:"text"`
	Confidence uint32 `json:"confidence"`
	Maturity   string `json:"maturity"`
	RefType    string `json:"ref_type"` // how this relates to the claim
}

// CounterFactSummary is a compact representation of a counter-fact.
type CounterFactSummary struct {
	ID           string `json:"id"`
	NegationType string `json:"negation_type"`
	Confidence   uint32 `json:"confidence"`
}

// IdentifyGapsPayload is the payload for identify_gaps commands.
type IdentifyGapsPayload struct {
	Domain    string        `json:"domain"`
	FactCount uint32        `json:"fact_count"`
	TopFacts  []FactSummary `json:"top_facts"`
}

// AnalyzeReferencesPayload is the payload for analyze_references commands.
type AnalyzeReferencesPayload struct {
	FactID    string        `json:"fact_id"`
	NodeCount int           `json:"node_count"`
	EdgeCount int           `json:"edge_count"`
	Depth     int           `json:"depth"`
	TopFacts  []FactSummary `json:"top_facts"`
}

// GenerateClaimPayload is the payload for generate_claim commands.
type GenerateClaimPayload struct {
	Domain string          `json:"domain"`
	Gaps   []GapSuggestion `json:"gaps"`
}

// OpenClawResponse is the typed response from an OpenClaw session.
type OpenClawResponse struct {
	Type       string            `json:"type"`
	Verdict    string            `json:"verdict,omitempty"`    // accept/reject/abstain
	Confidence uint32            `json:"confidence,omitempty"`
	Reasoning  string            `json:"reasoning,omitempty"`
	Gaps       []GapSuggestion   `json:"gaps,omitempty"`
	Claims     []ClaimSuggestion `json:"claims,omitempty"`
	Analysis   string            `json:"analysis,omitempty"`
	Error      string            `json:"error,omitempty"`
}

// GapSuggestion is a gap identified by OpenClaw AI reasoning.
type GapSuggestion struct {
	Type        string `json:"type"`
	Domain      string `json:"domain"`
	Description string `json:"description"`
	Priority    uint32 `json:"priority"` // BPS
}

// ClaimSuggestion is a claim generated by OpenClaw AI reasoning.
type ClaimSuggestion struct {
	Text     string `json:"text"`
	Domain   string `json:"domain"`
	Category string `json:"category"`
	Stake    uint64 `json:"stake"`
}

// DeployContractPayload is the payload for deploy_contract commands.
type DeployContractPayload struct {
	BytecodeHex string `json:"bytecode_hex"`
	Description string `json:"description,omitempty"` // Human-readable description of the contract
}

// CallContractPayload is the payload for call_contract commands.
type CallContractPayload struct {
	ContractAddr string `json:"contract_address"`
	InputDataHex string `json:"input_data_hex"`
	GasLimit     uint64 `json:"gas_limit,omitempty"` // 0 = default (500000)
}

// QueryContractPayload is the payload for query_contract commands.
type QueryContractPayload struct {
	ContractAddr string `json:"contract_address"`
	StorageKey   string `json:"storage_key"`
}

// ContractResult is the response for BVM contract operations.
type ContractResult struct {
	TxHash          string `json:"tx_hash,omitempty"`
	ContractAddress string `json:"contract_address,omitempty"`
	ReturnData      string `json:"return_data,omitempty"`
	StorageValue    string `json:"storage_value,omitempty"`
	GasUsed         uint64 `json:"gas_used,omitempty"`
}

// StructuredOpenClawManager wraps OpenClawManager with a typed JSON protocol.
type StructuredOpenClawManager struct {
	inner *OpenClawManager
}

// NewStructuredOpenClawManager creates a structured manager wrapping the raw one.
func NewStructuredOpenClawManager(inner *OpenClawManager) *StructuredOpenClawManager {
	return &StructuredOpenClawManager{inner: inner}
}

// sendRequest marshals a request, sends it, and unmarshals the response.
func (s *StructuredOpenClawManager) sendRequest(ctx context.Context, sessionID string, req *OpenClawRequest) (*OpenClawResponse, error) {
	data, err := json.Marshal(req)
	if err != nil {
		return nil, fmt.Errorf("marshaling request: %w", err)
	}

	rawResp, err := s.inner.SendCommand(ctx, sessionID, string(data))
	if err != nil {
		return nil, fmt.Errorf("sending command to session %s: %w", sessionID, err)
	}

	var resp OpenClawResponse
	if err := json.Unmarshal([]byte(rawResp), &resp); err != nil {
		// If the response isn't valid JSON, wrap it as reasoning text
		return &OpenClawResponse{
			Type:      req.Type,
			Reasoning: rawResp,
		}, nil
	}

	if resp.Error != "" {
		return nil, fmt.Errorf("openclaw error: %s", resp.Error)
	}

	return &resp, nil
}

// EvaluateClaim sends an evaluate_claim command and returns the verdict and confidence.
func (s *StructuredOpenClawManager) EvaluateClaim(ctx context.Context, sessionID string, payload EvaluateClaimPayload) (string, uint32, error) {
	payloadData, err := json.Marshal(payload)
	if err != nil {
		return "", 0, fmt.Errorf("marshaling payload: %w", err)
	}

	req := &OpenClawRequest{
		Type:    OCmdEvaluateClaim,
		Payload: payloadData,
	}

	resp, err := s.sendRequest(ctx, sessionID, req)
	if err != nil {
		return "", 0, err
	}

	verdict := resp.Verdict
	if verdict == "" {
		verdict = "abstain"
	}

	return verdict, resp.Confidence, nil
}

// IdentifyGaps sends an identify_gaps command and returns gap suggestions.
func (s *StructuredOpenClawManager) IdentifyGaps(ctx context.Context, sessionID, domain string, facts []FactSummary) ([]GapSuggestion, error) {
	payload := IdentifyGapsPayload{
		Domain:    domain,
		FactCount: uint32(len(facts)),
		TopFacts:  facts,
	}
	payloadData, err := json.Marshal(payload)
	if err != nil {
		return nil, fmt.Errorf("marshaling payload: %w", err)
	}

	req := &OpenClawRequest{
		Type:    OCmdIdentifyGaps,
		Payload: payloadData,
	}

	resp, err := s.sendRequest(ctx, sessionID, req)
	if err != nil {
		return nil, err
	}

	return resp.Gaps, nil
}

// AnalyzeReferences sends an analyze_references command and returns the analysis.
func (s *StructuredOpenClawManager) AnalyzeReferences(ctx context.Context, sessionID, factID string, subgraph *ReferenceSubgraph) (string, error) {
	topFacts := make([]FactSummary, 0, len(subgraph.Nodes))
	for _, node := range subgraph.Nodes {
		topFacts = append(topFacts, FactSummary{
			ID:         node.ID,
			Text:       node.ClaimText,
			Confidence: node.Confidence,
			Maturity:   node.Maturity,
		})
	}

	payload := AnalyzeReferencesPayload{
		FactID:    factID,
		NodeCount: len(subgraph.Nodes),
		EdgeCount: len(subgraph.Edges),
		Depth:     subgraph.Depth,
		TopFacts:  topFacts,
	}
	payloadData, err := json.Marshal(payload)
	if err != nil {
		return "", fmt.Errorf("marshaling payload: %w", err)
	}

	req := &OpenClawRequest{
		Type:    OCmdAnalyzeReferences,
		Payload: payloadData,
	}

	resp, err := s.sendRequest(ctx, sessionID, req)
	if err != nil {
		return "", err
	}

	if resp.Analysis != "" {
		return resp.Analysis, nil
	}
	return resp.Reasoning, nil
}

// GenerateClaim sends a generate_claim command and returns a claim suggestion.
func (s *StructuredOpenClawManager) GenerateClaim(ctx context.Context, sessionID, domain string, gaps []GapSuggestion) (*ClaimSuggestion, error) {
	payload := GenerateClaimPayload{
		Domain: domain,
		Gaps:   gaps,
	}
	payloadData, err := json.Marshal(payload)
	if err != nil {
		return nil, fmt.Errorf("marshaling payload: %w", err)
	}

	req := &OpenClawRequest{
		Type:    OCmdGenerateClaim,
		Payload: payloadData,
	}

	resp, err := s.sendRequest(ctx, sessionID, req)
	if err != nil {
		return nil, err
	}

	if len(resp.Claims) == 0 {
		return nil, fmt.Errorf("no claims generated")
	}

	return &resp.Claims[0], nil
}

// DeployContract sends a deploy_contract command and returns the result.
func (s *StructuredOpenClawManager) DeployContract(ctx context.Context, sessionID, bytecodeHex, description string) (*ContractResult, error) {
	payload := DeployContractPayload{
		BytecodeHex: bytecodeHex,
		Description: description,
	}
	payloadData, err := json.Marshal(payload)
	if err != nil {
		return nil, fmt.Errorf("marshaling payload: %w", err)
	}

	req := &OpenClawRequest{
		Type:    OCmdDeployContract,
		Payload: payloadData,
	}

	resp, err := s.sendRequest(ctx, sessionID, req)
	if err != nil {
		return nil, err
	}

	return &ContractResult{
		TxHash:          resp.Verdict,  // deploy returns tx hash in verdict field
		ContractAddress: resp.Analysis, // contract address in analysis field
		GasUsed:         uint64(resp.Confidence),
	}, nil
}

